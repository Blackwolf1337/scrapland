#!/usr/bin/env python3
# xctable.py [-w] [Scrap.exe]: the dynamic initializers of the game's globals for Crt_Main of ScrapC.exe
# (docs/standalone.md, stage 3c1b). The CRT of the original calls them from its __xc table (rva 0x3a15bc..0x3a31bc,
# _initterm); with -w this writes src/standalone/crtxc.inc, one CRT_XC(name, rva) line per entry in the order of the
# table, name the C function the hook at rva jumps to (src/hooks.inc). The zero entries and the CRT's own (its code
# from ORIG_CRT_CODE_START) are left out. Without -w it checks that the file is what it would write.
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sdexe import BASE, ROOT, SIZEOFIMAGE, TIMESTAMP, Exe, ExeError, c_names, define, header

XC_A, XC_Z = 0x3a15bc, 0x3a31bc	# the bounds the entry code pushes for _initterm (rva 0x3147f8)
OUT = os.path.join(ROOT, 'src', 'standalone', 'crtxc.inc')


def fail(msg):
	sys.exit('xctable.py: %s' % msg)


def table(x):
	crt_h = header('origcrt.h')
	crt = (define(crt_h, 'ORIG_CRT_CODE_START'), define(crt_h, 'ORIG_CRT_CODE_END'))
	hooks = c_names()
	lines = ['/* the dynamic initializers of the game\'s globals in the order of the __xc table of Scrap.exe 1.6.1 (rva',
		' * 0x%06x..0x%06x), for Crt_Main (crtxc.c); generated by tools/standalone/xctable.py, do not edit */' % (XC_A, XC_Z)]
	n = 0
	for at in range(XC_A, XC_Z, 4):
		v = x.u32(at)
		rva = v - BASE
		if not v or crt[0] <= rva < crt[1]:
			continue
		if rva not in hooks:
			fail('the initializer at rva %06x (entry %06x) has no C function' % (rva, at))
		lines.append('CRT_XC(%s, 0x%06x)' % (hooks[rva], rva))
		n += 1
	return '\n'.join(lines) + '\n', n


def main():
	args = sys.argv[1:]
	write = '-w' in args
	rest = [a for a in args if a != '-w']
	try:
		x = Exe(rest[0] if rest else os.path.join(ROOT, 'game', 'Bin', 'Scrap.exe'))
	except ExeError as e:
		fail(str(e))
	if x.stamp != TIMESTAMP or x.size != SIZEOFIMAGE:
		fail('not Scrap.exe 1.6.1')
	text, n = table(x)
	if write:
		open(OUT, 'w').write(text)
		print('xctable.py: wrote %d initializers to %s' % (n, os.path.relpath(OUT, ROOT)))
		return
	if not os.path.exists(OUT) or open(OUT).read() != text:
		fail('%s is not what -w writes' % os.path.relpath(OUT, ROOT))
	print('xctable.py: %d initializers, %s is up to date' % (n, os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
	main()
