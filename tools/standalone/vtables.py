#!/usr/bin/env python3
# vtables.py [-w] [Scrap.exe]: the vtables of the game classes as C for ScrapC.exe (docs/standalone.md, stage 3b1).
# Finds them from the RTTI of Scrap.exe 1.6.1 (a pointer to a complete object locator before each one, its slots the
# relocated code pointers after it) and names each slot by the C function its hook jumps to (src/hooks.inc, the
# CRT entries). A slot without a C function stops it. With -w it writes src/game/Global/Vtables.c. It also checks that
# every GAME_VFTABLE(name, rva) in src/ and include/ names the vtable at that rva.
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sdexe import ROOT, Exe, ExeError, c_names, english

OUT = 'src/game/Global/Vtables.c'

# the classes of the libraries in the copy, their vtables stay bytes of the original: the C++ runtime (type_info, the
# std exceptions, the name nodes of its undecorator), nothing of the C calls them
LIBRARY = re.compile(r'^\.\?AV(type_info|\w+@std|DNameNode|charNode|pcharNode|pDNameNode|DNameStatusNode|pairNode)@@$')
# the classes of the original's GOG Galaxy and Steam code (the listeners, the Steam callbacks): the C has none of it
STORE = re.compile(r'^\.\?AV(\?\$)?CCallback|@(galaxy|gog)@@$')

# the template classes by hand (MSVC encodes the integer arguments: $06 is 7, $07 is 8)
TEMPLATES = {
	'.?AV?$cBinaryHeap@PAUElemAStar@@@@': 'cBinaryHeap_ElemAStar',
	'.?AV?$cGridElements@UInfoTrafficNode@@@@': 'cGridElements_InfoTrafficNode',
	'.?AV?$cGridElements@PAUInfPointVis@@@@': 'cGridElements_InfPointVis',
}


def fail(msg):
	sys.exit('vtables.py: %s' % msg)


def class_name(td):
	"""the C name of the class of a type descriptor name: namespaces first, joined by _, in English (the RTTI names
	are the Spanish ones of the original: CEscena is CScene)"""
	if td in TEMPLATES:
		return TEMPLATES[td]
	m = re.match(r'^\.\?A[UV]([A-Za-z_]\w*(?:@[A-Za-z_]\w*)*)@@$', td)
	if not m:
		fail('no C name for the class %s: add it to TEMPLATES' % td)
	return english('_'.join(reversed(m.group(1).split('@'))))


def find(x):
	"""the vtables of the exe: [(rva, type descriptor name, [slot target rvas])] in rva order"""
	def insec(r, s):
		va, n, ptr, vsize = x.secs[s]
		return va <= r < va + max(n, vsize)

	def cstr(r):
		o = x.off(r)
		return x.b[o:x.b.index(b'\0', o)].decode('latin1')

	out = []
	for at in sorted(x.relocs()):
		col = x.ptr(at)
		if not insec(at, '.rdata') or col is None or not insec(col, '.rdata') or x.off(col) is None or x.u32(col):
			continue
		td = x.ptr(col + 12)
		if td is None or not insec(td, '.data') or not cstr(td + 8).startswith('.?A'):
			continue
		if x.u32(col + 4):
			fail('the vtable at rva %06x is not the first of its class (offset %x)' % (at + 4, x.u32(col + 4)))
		slots = []
		s = at + 4
		while True:
			t = x.ptr(s)
			if t is None or not insec(t, '.text'):
				break
			slots.append(t)
			s += 4
		if slots:
			out.append((at + 4, cstr(td + 8), slots))
	return out


def main():
	args = [a for a in sys.argv[1:] if a != '-w']
	try:
		x = Exe(args[0] if args else os.path.join(ROOT, 'game/Bin/Scrap.exe'))
	except ExeError as e:
		fail(str(e))
	hooks = c_names()
	game = []
	names = set()
	for rva, td, slots in find(x):
		if LIBRARY.match(td) or STORE.search(td):
			continue
		name = class_name(td) + '_vftable'
		if name in names:
			fail('two vtables named %s' % name)
		names.add(name)
		for i, t in enumerate(slots):
			if t not in hooks:
				fail('%s (rva %06x): slot %d leads to rva %06x, which has no C function' % (name, rva, i, t))
		game.append((rva, td, name, slots))
	byrva = {rva: name for rva, td, name, slots in game}

	# the GAME_VFTABLE uses of the C
	bad = 0
	uses = 0
	for top in ('src', 'include'):
		for d, _, fs in os.walk(os.path.join(ROOT, top)):
			for f in fs:
				if not f.endswith(('.c', '.h', '.inc')):
					continue
				path = os.path.join(d, f)
				for name, rva in re.findall(r'GAME_VFTABLE\((\w+), (0x[0-9a-fA-F]+)\)', open(path).read()):
					uses += 1
					if byrva.get(int(rva, 16)) != name:
						bad += 1
						print('vtables.py: %s: GAME_VFTABLE(%s, %s), the vtable there is %s'
							% (os.path.relpath(path, ROOT), name, rva, byrva.get(int(rva, 16), 'none')))
	print('vtables.py: %d vtables of game classes, %d slots; %d GAME_VFTABLE uses' % (len(game),
		sum(len(g[3]) for g in game), uses))
	if bad:
		fail('%d GAME_VFTABLE uses name another vtable' % bad)
	if '-w' not in sys.argv:
		return

	funcs = sorted(set(hooks[t] for g in game for t in g[3]))
	lines = [
		'/*',
		' * The vtables of the game classes in ScrapC.exe (docs/standalone.md, stage 3b1), generated by',
		' * tools/standalone/vtables.py from the RTTI of Scrap.exe 1.6.1 and the hooks, do not edit. Each one lies at the',
		' * rva of the original\'s (SD_AT), its slots are the C functions the hooks of the original slots jump to (the',
		' * comment has the offset and the original rva). The complete object locator before each one stays the',
		' * original\'s. The hook DLL uses the exe\'s own vtables. The C reaches them through GAME_VFTABLE (scrap/game.h).',
		' */',
		'#include "scrap/shared.h"',
		'',
		'#ifdef SD_STANDALONE',
		'',
		'/* only the addresses are needed here, as in src/core/hook.c */',
	]
	lines += ['void %s(void);' % f for f in funcs]
	for rva, td, name, slots in game:
		lines += ['', '/* %s */' % td, 'void (*const %s[%d])(void) SD_AT(0x%06x) = {' % (name, len(slots), rva)]
		lines += ['\t%s,\t/* 0x%02x 0x%06x */' % (hooks[t], 4 * i, t) for i, t in enumerate(slots)]
		lines.append('};')
	lines += ['', '#endif', '']
	open(os.path.join(ROOT, OUT), 'w').write('\n'.join(lines))
	print('vtables.py: wrote %s' % OUT)


main()
