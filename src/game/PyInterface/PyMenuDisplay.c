/*
 * ScrapC's addition to the video options of the menu (PCMenu of the script pack): a Display entry with Windowed,
 * Borderless and Fullscreen for the FullScreen engine variable (0, 2, 1). It wraps PCMenu.VideoMenu (the entry is
 * appended after the menu is built: an item added at the front is drawn first, under the panel) and
 * PCMenu.ApplyChanges (the mode is set before the original applies the rest, an engine reset applies it); the game
 * files stay as they are. The texts are in the extra entries of Language.c.
 */
#include "scrap/python.h"
#include "scrap/scrap.h"

static const char pyMenuDisplay[] =
	"import Scrap, SScorer\n"
	"try:\n"
	"\timport PCMenu, Menu\n"
	"except:\n"
	"\tPCMenu = None\n"
	"if PCMenu and not hasattr(PCMenu, 'ScrapC_OrigVideoMenu'):\n"
	"\tdef ScrapC_DisplayNames():\n"
	"\t\timport Scrap\n"
	"\t\treturn (Scrap.GetLangStr('Menu_Video_Windowed'), Scrap.GetLangStr('Menu_Video_Fullscreen'),\n"
	"\t\t\tScrap.GetLangStr('Menu_Video_Borderless'))\n"
	"\tdef ScrapC_DisplayIndex(id):\n"
	"\t\timport PCMenu, SScorer, Scrap\n"
	"\t\tnames = PCMenu.ScrapC_DisplayNames()\n"
	"\t\ttext = SScorer.Get(id, 'Display', 'Text')\n"
	"\t\tfor i in range(3):\n"
	"\t\t\tif names[i] == text:\n"
	"\t\t\t\treturn i\n"
	"\t\ti = Scrap.Get('FullScreen')\n"
	"\t\tif i < 0 or i > 2:\n"
	"\t\t\ti = 1\n"
	"\t\treturn i\n"
	"\tdef ScrapC_VideoMenu(id, control):\n"
	"\t\timport PCMenu, SScorer, Scrap\n"
	"\t\tPCMenu.ScrapC_OrigVideoMenu(id, control)\n"
	"\t\titems =(('TitleDisplay', Scrap.GetLangStr('Menu_Video_Display') + ':', 440, (143, 180, 215)),\n"
	"\t\t\t('Display', 'WWWWWWWWWW', 450, (183, 220, 255)))\n"
	"\t\tfor iname, text, x, color in items:\n"
	"\t\t\tSScorer.Add(id, iname, 'Text', 1)\n"
	"\t\t\tSScorer.Set(id, iname, 'Font', 'Horatio')\n"
	"\t\t\tSScorer.Set(id, iname, 'Text', text)\n"
	"\t\t\tSScorer.Set(id, iname, 'CentralText', 1)\n"
	"\t\t\tSScorer.Set(id, iname, 'X', x)\n"
	"\t\t\tSScorer.Set(id, iname, 'Y', 228)\n"
	"\t\t\tif iname == 'TitleDisplay':\n"
	"\t\t\t\tSScorer.Set(id, iname, 'Align', 'Right')\n"
	"\t\t\t\tSScorer.Set(id, iname, 'GetExtens', 1)\n"
	"\t\t\tSScorer.Set(id, iname, 'Align', 'Left')\n"
	"\t\t\tSScorer.Set(id, iname, 'Red', color[0])\n"
	"\t\t\tSScorer.Set(id, iname, 'Green', color[1])\n"
	"\t\t\tSScorer.Set(id, iname, 'Blue', color[2])\n"
	"\t\t\tSScorer.Set(id, iname, 'Effect', 'Shadow')\n"
	"\t\t\tSScorer.Set(id, iname, 'OnAccept', 'PCMenu.ChangeDisplay')\n"
	"\t\tSScorer.Set(id, 'Display', 'Text', PCMenu.ScrapC_DisplayNames()[PCMenu.ScrapC_DisplayIndex(id)])\n"
	"\t\tSScorer.Set(id, 'TitleTextureDetail', 'Right', 'TitleDisplay')\n"
	"\t\tSScorer.Set(id, 'TitleDisplay', 'Left', 'TitleTextureDetail')\n"
	"\t\tSScorer.Set(id, 'TitleDisplay', 'Up', 'VideoModeNext')\n"
	"\t\tSScorer.Set(id, 'TitleDisplay', 'Down', 'TitleFog')\n"
	"\tdef ScrapC_ChangeDisplay(id, control):\n"
	"\t\timport PCMenu, SScorer\n"
	"\t\tPCMenu.Apply_SetActive(id, control)\n"
	"\t\tnext = (2, 0, 1)[PCMenu.ScrapC_DisplayIndex(id)]\n"
	"\t\tSScorer.Set(id, 'Display', 'Text', PCMenu.ScrapC_DisplayNames()[next])\n"
	"\tdef ScrapC_ApplyChanges(id, control):\n"
	"\t\timport PCMenu, Scrap\n"
	"\t\tmode = PCMenu.ScrapC_DisplayIndex(id)\n"
	"\t\tchanged = mode != Scrap.Get('FullScreen')\n"
	"\t\tScrap.Set('FullScreen', mode)\n"
	"\t\tPCMenu.ScrapC_OrigApplyChanges(id, control)\n"
	"\t\tif changed:\n"
	"\t\t\tScrap.SetVideoCurrentMode(PCMenu.SelectedVideoMode)\n"
	"\tPCMenu.ScrapC_OrigVideoMenu = PCMenu.VideoMenu\n"
	"\tPCMenu.ScrapC_OrigApplyChanges = PCMenu.ApplyChanges\n"
	"\tPCMenu.ScrapC_DisplayNames = ScrapC_DisplayNames\n"
	"\tPCMenu.ScrapC_DisplayIndex = ScrapC_DisplayIndex\n"
	"\tPCMenu.ChangeDisplay = ScrapC_ChangeDisplay\n"
	"\tPCMenu.VideoMenu = ScrapC_VideoMenu\n"
	"\tPCMenu.ApplyChanges = ScrapC_ApplyChanges\n"
	"\tdel ScrapC_DisplayNames, ScrapC_DisplayIndex, ScrapC_VideoMenu, ScrapC_ChangeDisplay, ScrapC_ApplyChanges\n";

void PyMenu_AddDisplayOption(void) {
	PyRun_SimpleString((char *)pyMenuDisplay);
}
